"""Build the v9 Tarot meaning refresh from reviewable locale JSON files."""
from __future__ import annotations

import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRANSLATIONS = ROOT / "database" / "translations"
OUTPUT = ROOT / "database" / "migrations" / "009_refresh_card_meanings.sql"
LOCALES = ("es-419", "pt-BR", "id", "hi", "th", "fr", "de", "ja", "ko")


def quote(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def generate() -> str:
    connection = sqlite3.connect(":memory:")
    for name in ("migrations/001_initial.sql", "seeds/001_major_arcana.sql", "seeds/002_minor_arcana.sql"):
        connection.executescript((ROOT / "database" / name).read_text(encoding="utf-8"))
    ids = [row[0] for row in connection.execute("SELECT id FROM tarot_cards ORDER BY deck_order")]
    connection.close()
    english = json.loads((TRANSLATIONS / "cards.en.json").read_text(encoding="utf-8"))
    if set(english) != set(ids):
        raise ValueError("English meaning coverage must contain exactly 78 cards")
    lines = [
        "-- Generated by database/scripts/build_meaning_migration.py.",
        "-- Edit database/translations/cards.<locale>.json, then regenerate this migration.",
        "BEGIN;",
    ]
    for card_id in ids:
        lines.append(
            f"UPDATE tarot_cards SET meaning = {quote(english[card_id])} WHERE id = {quote(card_id)};"
        )
    for locale in LOCALES:
        cards = json.loads((TRANSLATIONS / f"cards.{locale}.json").read_text(encoding="utf-8"))
        if set(cards) != set(ids):
            raise ValueError(f"{locale} meaning coverage must contain exactly 78 cards")
        for card_id in ids:
            fields = cards[card_id]
            if set(fields) != {"name", "meaning", "advice", "yesNoMeaning"}:
                raise ValueError(f"Invalid fields in {locale}.{card_id}")
            payload = json.dumps(fields, ensure_ascii=False, separators=(",", ":"))
            lines.append(
                f"UPDATE card_translations SET payload = {quote(payload)} "
                f"WHERE card_id = {quote(card_id)} AND locale = {quote(locale)};"
            )
    lines += ["PRAGMA user_version = 9;", "COMMIT;", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    expected = generate()
    if "--check" in sys.argv:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Meaning migration is stale; run build_meaning_migration.py")
        print("PASS: meaning migration matches source JSON")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT}")
