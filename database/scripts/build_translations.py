"""Generate the multilingual SQLite seed from reviewable locale JSON files.

Vietnamese keeps its compact, hand-reviewed source format. New locales use
explicit payload objects so translators can review every stored field without
language-specific template code.
"""
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRANSLATIONS = ROOT / "database" / "translations"
OUTPUT = ROOT / "database" / "seeds" / "004_translations.sql"
LEGACY_VI_OUTPUT = ROOT / "database" / "seeds" / "003_translations_vi.sql"
SUPPORTED_LOCALES = ("vi", "es-419", "pt-BR", "id", "hi", "th", "fr", "de", "ja", "ko", "zh-TW")
CARD_FIELDS = ("name", "meaning", "advice", "yesNoMeaning")
SIGN_FIELDS = ("name", "dateRange", "rulingPlanet", "summary", "originStory", "traits", "strengths", "challenges", "compatibleSigns", "reflectionPrompt")
HOROSCOPE_FIELDS = ("overview", "love", "career", "finance", "wellbeing", "guidance")


def read(name: str):
    return json.loads((TRANSLATIONS / name).read_text(encoding="utf-8"))


def validate_payload(value, fields, label: str):
    if not isinstance(value, dict) or set(value) != set(fields):
        raise AssertionError(f"{label} must contain exactly: {', '.join(fields)}")
    for field in fields:
        items = value[field] if isinstance(value[field], list) else [value[field]]
        if not items or not all(isinstance(item, str) and item.strip() for item in items):
            raise AssertionError(f"{label}.{field} must be non-empty")
    return value


def generate(included_locales: set[str] | None = None) -> str:
    db = sqlite3.connect(":memory:")
    for name in ["migrations/001_initial.sql", "migrations/002_zodiac.sql",
                 "migrations/003_translations.sql", "migrations/004_expand_locales.sql",
                 "seeds/001_major_arcana.sql", "seeds/002_minor_arcana.sql", "seeds/003_zodiac.sql"]:
        db.executescript((ROOT / "database" / name).read_text(encoding="utf-8"))
    source_cards = db.execute("SELECT id, yes_no FROM tarot_cards ORDER BY deck_order").fetchall()
    source_signs = db.execute("SELECT id, element FROM zodiac_signs ORDER BY display_order").fetchall()
    card_ids = {row[0] for row in source_cards}
    sign_ids = {row[0] for row in source_signs}

    discovered = {
        path.name[len("cards."):-len(".json")]
        for path in TRANSLATIONS.glob("cards.*.json")
    }
    # cards.en.json is the v9 English meaning source for the base table, not a
    # card_translations locale pack.
    unknown = discovered.difference((*SUPPORTED_LOCALES, "en"))
    assert not unknown, f"Unregistered database locales: {sorted(unknown)}"
    assert "vi" in discovered, "Vietnamese translation source is required"

    lines = [
        "-- Generated by build_translations.py. Edit database/translations locale JSON files.",
        "BEGIN;"
    ]

    def insert(table, columns, values):
        literals = ["'" + str(value).replace("'", "''") + "'" for value in values]
        lines.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join(literals)});")

    def payload(value):
        return json.dumps(value, ensure_ascii=False, separators=(",", ":"))

    for locale in SUPPORTED_LOCALES:
        if locale not in discovered:
            continue
        if included_locales is not None and locale not in included_locales:
            continue

        if locale == "vi":
            cards = read("cards.vi.json")
            signs = read("zodiac.vi.json")
            periods = read("periods.vi.json")
            assert set(cards) == card_ids, "Vietnamese card translation coverage mismatch"
            assert set(signs) == sign_ids, "Vietnamese zodiac translation coverage mismatch"
            assert set(periods) == {"day", "week", "year"}
            verdict = {"yes": "nghiêng về có", "no": "nghiêng về không", "maybe": "còn tùy điều kiện", "uncertain": "chưa rõ câu trả lời"}
            elements = {"fire": "Lửa", "earth": "Đất", "air": "Khí", "water": "Nước"}
            for card_id, answer in source_cards:
                row = cards[card_id]
                assert len(row) in (3, 4) and all(isinstance(v, str) and v.strip() for v in row)
                name, meaning, advice = row[:3]
                explanation = row[3] if len(row) == 4 else f"{name} {verdict[answer]}: {advice[0].lower() + advice[1:]}"
                content = dict(name=name, meaning=meaning, advice=advice, yesNoMeaning=explanation)
                insert("card_translations", ["card_id", "locale", "payload"], [card_id, locale, payload(content)])
            for sign_id, element in source_signs:
                sign = validate_payload(signs[sign_id], SIGN_FIELDS, f"{locale}.zodiac.{sign_id}")
                insert("zodiac_translations", ["sign_id", "locale", "payload"], [sign_id, locale, payload(sign)])
                for period, copy in periods.items():
                    assert len(copy) == 6
                    content = dict(
                        overview=f"{copy[0]} {sign['name']} mang năng lượng {elements[element]}. {sign['summary']}",
                        love=f"{copy[1]} Thế mạnh {', '.join(sign['strengths']).lower()} giúp bạn kết nối mà không cần gồng mình thể hiện.",
                        career=f"{copy[2]} Dùng {', '.join(sign['traits']).lower()} làm công cụ, không phải kỳ vọng phải đáp ứng cùng lúc.",
                        finance=f"{copy[3]} Nhận ra khi {', '.join(sign['challenges']).lower()} bắt đầu ảnh hưởng tới quyết định thực tế.",
                        wellbeing=f"{copy[4]} {sign['reflectionPrompt']}",
                        guidance=f"{copy[5]} {sign['reflectionPrompt']}"
                    )
                    insert("horoscope_translations", ["sign_id", "period", "locale", "payload"], [sign_id, period, locale, payload(content)])
            continue

        cards = read(f"cards.{locale}.json")
        signs = read(f"zodiac.{locale}.json")
        horoscopes = read(f"horoscope.{locale}.json")
        assert set(cards) == card_ids, f"{locale} card translation coverage mismatch"
        assert set(signs) == sign_ids, f"{locale} zodiac translation coverage mismatch"
        assert set(horoscopes) == sign_ids, f"{locale} horoscope sign coverage mismatch"
        for card_id, _ in source_cards:
            content = validate_payload(cards[card_id], CARD_FIELDS, f"{locale}.cards.{card_id}")
            insert("card_translations", ["card_id", "locale", "payload"], [card_id, locale, payload(content)])
        for sign_id, _ in source_signs:
            sign = validate_payload(signs[sign_id], SIGN_FIELDS, f"{locale}.zodiac.{sign_id}")
            insert("zodiac_translations", ["sign_id", "locale", "payload"], [sign_id, locale, payload(sign)])
            periods = horoscopes[sign_id]
            assert set(periods) == {"day", "week", "year"}, f"{locale}.{sign_id} horoscope period coverage mismatch"
            for period in ("day", "week", "year"):
                content = validate_payload(periods[period], HOROSCOPE_FIELDS, f"{locale}.horoscope.{sign_id}.{period}")
                insert("horoscope_translations", ["sign_id", "period", "locale", "payload"], [sign_id, period, locale, payload(content)])

    db.close()
    return "\n".join([*lines, "COMMIT;", ""])


if __name__ == "__main__":
    import sys
    generated = generate()
    legacy_vi_generated = generate({"vi"})
    if "--check" in sys.argv:
        assert OUTPUT.read_text(encoding="utf-8") == generated, "Run python ../database/scripts/build_translations.py to refresh the translation seed"
        assert LEGACY_VI_OUTPUT.read_text(encoding="utf-8") == legacy_vi_generated, "Run python ../database/scripts/build_translations.py to refresh the legacy Vietnamese translation seed"
        print("PASS: translation seed matches source JSON")
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
        LEGACY_VI_OUTPUT.write_text(legacy_vi_generated, encoding="utf-8", newline="\n")
        print(f"Generated {OUTPUT}")
        print(f"Generated {LEGACY_VI_OUTPUT}")
